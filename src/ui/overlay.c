static const uint32_t ov_keys[] = {0x4024F153u, 0x1C975906u, 0x11A5507Eu, 0x3CE06DC2u, 0x38D8DDD3u, 0x6BEE141Du};


void ov_decode(int id, const uint8_t *in, size_t n, char *out)
{
    for (size_t i = 0; i < n; i++)
        out[i] = (char)(in[i] ^ ((0xA7 + id * 29 + (int)i * 13) & 0xFF));
    out[n] = '\0';
}

size_t ov_text(int id, char *out, size_t cap)
{
    if (id < 0 || id >= OV_TEXTS || cap == 0) {
        if (cap)
            out[0] = '\0';
        return 0;
    }
    size_t n = ov_index[id][1];
    char buf[OV_TEXT_MAX + 1];
    ov_decode(id, ov_blob + ov_index[id][0], n, buf);
    if (n > cap - 1)
        n = cap - 1;
    memcpy(out, buf, n);
    out[n] = '\0';
    return n;
}

/* FNV-1a of the prompt in lower case, words separated by single spaces. */
static uint32_t prompt_key(const char *s)
{
    uint32_t h = 0x811C9DC5u;
    int gap = 0, any = 0;
    for (; *s; s++) {
        unsigned char c = (unsigned char)*s;
        if (!isalnum(c)) {
            gap = 1;
            continue;
        }
        if (gap && any)
            h = (h ^ ' ') * 0x01000193u;
        h = (h ^ (uint32_t)tolower(c)) * 0x01000193u;
        gap = 0;
        any = 1;
    }
    return any ? h : 0;
}

int ov_match(const char *prompt)
{
    uint32_t k = prompt_key(prompt);
    for (size_t i = 0; k && i < sizeof ov_keys / sizeof ov_keys[0]; i++)
        if (ov_keys[i] == k)
            return 1;
    return 0;
}

void ov_start(ov_player *p)
{
    memset(p, 0, sizeof *p);
    p->typing = -1;
}

static void line_cmd(const ov_step *s, int len, ov_cmd *c)
{
    c->op = s->op;
    c->screen = s->screen;
    c->colour = s->colour;
    c->flags = s->flags;
    c->row = s->row;
    c->arg = s->arg;
    c->len = (uint8_t)len;
}

int ov_poll(ov_player *p, ov_cmd *c)
{
    if (p->done || p->wait > 0)
        return 0;
    if (p->typing >= 0) {
        const ov_step *s = &script[p->typing];
        line_cmd(s, ++p->shown, c);
        if (p->shown >= p->len) {
            p->typing = -1;
            p->wait = s->hold;
        } else {
            p->wait = OV_TYPE_FRAMES;
        }
        return 1;
    }
    const ov_step *s = &script[p->i];
    if (s->op == OV_END) {
        p->done = 1;
        line_cmd(s, 0, c);
        return 1;
    }
    p->i++;
    int len = s->op == OV_LINE ? (int)ov_index[s->arg][1] : 0;
    if (s->op == OV_LINE && (s->flags & OV_TYPED)) {
        p->typing = p->i - 1;
        p->len = len;
        p->shown = 1;
        p->wait = len > 1 ? OV_TYPE_FRAMES : s->hold;
        if (len <= 1)
            p->typing = -1;
        line_cmd(s, 1, c);
        return 1;
    }
    p->wait = s->hold;
    line_cmd(s, len, c);
    return 1;
}

int ov_advance(ov_player *p)
{
    if (p->done)
        return 0;
    p->frames++;
    if (p->wait > 0)
        p->wait--;
    return 1;
}

int ov_length(void)
{
    ov_player p;
    ov_cmd c;
    ov_start(&p);
    do {
        while (ov_poll(&p, &c))
            ;
    } while (ov_advance(&p));
    return p.frames + 1; /* the frame that ends it */
}
