#!/usr/bin/env python3
"""Generate src/engine/fxtables.h: constants for the fixed-point engine.

Tables are computed here, correctly rounded, and compiled in, so the DS and
the host build use identical values (no libm at run time).

    python tools/gen_fxtables.py          write the header
    python tools/gen_fxtables.py --check  exit 1 if the header is stale
"""
import math
import pathlib
import sys

OUT = pathlib.Path(__file__).resolve().parent.parent / "src" / "engine" / "fxtables.h"


def q(x, bits):
    return int(math.floor(x * (1 << bits) + 0.5))


def render():
    exp2 = [q(2.0 ** (k / 256.0), 30) for k in range(257)]
    rows = []
    for i in range(0, 257, 6):
        rows.append("    " + ", ".join(f"{v}u" for v in exp2[i:i + 6]) + ",")
    return f"""/* Generated by tools/gen_fxtables.py; do not edit. */
#ifndef DSLM_FXTABLES_H
#define DSLM_FXTABLES_H

#include <stdint.h>

/* 2^(k/256) for k = 0..256, Q30 */
static const uint32_t FX_EXP2_Q30[257] = {{
{chr(10).join(rows)}
}};

#define FX_LOG2E_Q30 {q(math.log2(math.e), 30)}LL       /* log2(e) */
#define FX_LOG2_10000_Q16 {q(math.log2(10000.0), 16)}LL /* log2(10000), RoPE base */
#define FX_PI_Q30 {q(math.pi, 30)}LL
#define FX_HALF_PI_Q30 {q(math.pi / 2, 30)}LL
#define FX_TWO_PI_Q30 {q(2 * math.pi, 30)}LL

#endif
"""


def main():
    text = render()
    if "--check" in sys.argv:
        ok = OUT.exists() and OUT.read_text(encoding="utf-8") == text
        print("fxtables up to date" if ok else "fxtables STALE: run python tools/gen_fxtables.py")
        return 0 if ok else 1
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
